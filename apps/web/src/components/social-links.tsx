export function SocialLinks({
  profile,
  className = "site-footer__socials",
  itemClassName = "site-footer__social",
}: SocialLinksProps) {
  const socials = [
    profile.linkedin
      ? { href: profile.linkedin, label: "LinkedIn", icon: <LinkedinIcon /> }
      : null,
    profile.github
      ? { href: profile.github, label: "GitHub", icon: <GithubIcon /> }
      : null,
    profile.facebook
      ? { href: profile.facebook, label: "Facebook", icon: <FacebookIcon /> }
      : null,
  ].filter(Boolean) as Array<{
    href: string;
    label: string;
    icon: React.ReactElement;
  }>;

  if (socials.length === 0) {
    return null;
  }

  return (
    <ul className={className} aria-label="Réseaux sociaux">
      {socials.map((social) => (
        <li key={social.label}>
          <a
            className={itemClassName}
            href={social.href}
            target="_blank"
            rel="noreferrer"
            aria-label={social.label}
            title={social.label}
          >
            {social.icon}
          </a>
        </li>
      ))}
    </ul>
  );
}
