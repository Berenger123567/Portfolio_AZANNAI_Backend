export function getFallbackProject(slug: string): ProjectDetailData | null {
  const project = fallbackSiteData.projects.find((p) => p.slug === slug);
  if (!project) return null;

  const currentIndex = fallbackSiteData.projects.findIndex((p) => p.slug === slug);
  const nextProject =
    currentIndex < fallbackSiteData.projects.length - 1
      ? {
          slug: fallbackSiteData.projects[currentIndex + 1].slug,
          plate: fallbackSiteData.projects[currentIndex + 1].plate,
          title: fallbackSiteData.projects[currentIndex + 1].title,
        }
      : null;

  return {
    project,
    nextProject,
  };
}
